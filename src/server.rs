    #[tool(
        description = "Disassemble a ROM without keeping a session open (starts a transient \
        headless debugger, dumps the disassembly, and exits)."
    )]
    async fn rom_disassemble(
        &self,
        Parameters(args): Parameters<RomDisasmArgs>,
    ) -> Result<CallToolResult, McpError> {
        let helper = self
            .inner
            .toolchain
            .helper
            .clone()
            .ok_or_else(|| internal_msg("helper binary not built; run build_emulator first"))?;
        if !args.rom_path.is_file() {
            return Err(internal_msg(&format!(
                "ROM not found: {}",
                args.rom_path.display()
            )));
        }
        let session = Session::start(
            "tmp",
            &helper,
            &args.rom_path,
            args.mapping.as_deref(),
            None,
        )
        .await
        .map_err(internal)?;
        // Gopher2600 builds its disassembly as code executes, so run a frame to
        // populate the reachable code before dumping it.
        let _ = session.send("STEP FRAME").await.map_err(internal)?;
        let res = session.send("DISASM SEQUENTIAL").await.map_err(internal)?;
        session.stop().await;
        Ok(reply(&res))
    }

