        description = "Assemble an Atari 2600 ROM from DASM / 8bitworkshop assembly source. \
        Bundled vcs.h/macro.h are on the include path. Writes a .bin and a .sym (auto-loaded by \
        the debugger for symbolic disassembly). Returns the ROM path."
