//! The MCP server: tool definitions that drive the Gopher2600 debugger.
//!
//! [`StellaMcp`] exposes a session lifecycle plus a full interactive debugger
//! surface (execution control, breakpoints/traps/watches, memory and register
//! inspection, chip state, disassembly, and ARM-coprocessor/DWARF debugging).
//! Most tools map to a single debugger command; [`StellaMcp::debugger_command`]
//! is an escape hatch for anything not wrapped.

