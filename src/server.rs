    #[tool(
        description = "Capture the current TV frame as a PNG and return it inline. Step or \
        run the emulation at least one frame first. Optionally specify an output path."
    )]
    async fn screenshot(
        &self,
        Parameters(args): Parameters<ScreenshotArgs>,
    ) -> Result<CallToolResult, McpError> {
        let session = self.resolve(args.session).await?;
        let path = if let Some(p) = args.path {
            std::path::absolute(&p).map_err(internal)?
        } else {
            let n = self.inner.shots.fetch_add(1, Ordering::Relaxed) + 1;
            std::env::temp_dir()
                .join("stella-mcp")
                .join(format!("{}-{n}.png", session.id))
        };
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(internal)?;
        }

        let res = session
            .send(&format!("SCREENSHOT {}", path.display()))
            .await
            .map_err(internal)?;
        if res.error {
            return Ok(reply(&res));
        }

        let bytes = std::fs::read(&path).map_err(|e| {
            internal_msg(&format!(
                "screenshot saved but unreadable ({e}): {}",
                path.display()
            ))
        })?;
        let encoded = base64::engine::general_purpose::STANDARD.encode(&bytes);
        Ok(CallToolResult::success(vec![
            Content::text(format!("{}\n{}", res.text, path.display())),
            Content::image(encoded, "image/png"),
        ]))
    }

